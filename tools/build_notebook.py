def build() -> nbf.NotebookNode:
    nb = nbf.v4.new_notebook()
    cells = [md(INTRO), md(BEFORE), code(GPU_CELL)]

    # Inside section 1 on purpose: `%%writefile` cannot create directories, so
    # the folders must exist before the first source cell - even when somebody
    # re-runs only this section on a fresh runtime.
    cells.append(md(SOURCES_NOTE))
    cells.append(code(DIRS_CELL))

    # Sources first: setup_colab.sh imports `s2p` for its final smoke test.
    cells.append(writefile_cell("requirements-colab.txt"))
    cells.append(writefile_cell("constraints.txt"))
    cells.append(writefile_cell("scripts/setup_colab.sh"))
    cells.append(writefile_cell("scripts/download_checkpoints.py"))
    for module in MODULES:
        cells.append(writefile_cell(f"s2p/{module}"))

    cells.append(md(SETUP_NOTE))
    cells.append(code(SETUP_CELL))
    cells.append(code(PREFLIGHT_CELL))

    cells.append(md(INPUT_NOTE))
    cells.append(code(PORTRAIT_CELL))
    cells.append(nbf.v4.new_code_cell(
        f"%%writefile /content/input/script.txt\n{DEMO_SCRIPT}"
    ))
    cells.append(md(SCRIPT_NOTE))

    cells.append(md(GENERATE_NOTE))
    cells.append(code(GENERATE_CELL))
    cells.append(code(RESULT_CELL))
    cells.append(code(DOWNLOAD_CELL))

    cells.append(md(UI_NOTE))
    cells.append(code(UI_CELL))

    cells.append(md(TROUBLESHOOTING))
    cells.append(md(HOW_IT_WORKS))
    cells.append(md(CREDITS))

    nb.cells = cells

    # nbformat generates a random id per cell, which would make the generated file
    # differ on every run. Stable ids keep `--check` (and the sync test) meaningful.
    for index, cell in enumerate(nb.cells):
        cell["id"] = f"cell-{index:03d}"

    nb.metadata = {
        "colab": {"provenance": [], "gpuType": "T4", "toc_visible": True},
        "kernelspec": {"display_name": "Python 3", "name": "python3"},
        "language_info": {"name": "python"},
        "accelerator": "GPU",
    }
    return nb


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when the notebook on disk is out of date")
    args = parser.parse_args(argv)

    nb = build()
    text = nbf.writes(nb) + "\n"

    if args.check:
        if not OUTPUT.is_file():
            print(f"{OUTPUT.name} is missing - run tools/build_notebook.py")
            return 1
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.name} is out of date - run tools/build_notebook.py")
            return 1
        print(f"{OUTPUT.name} is up to date ({len(nb.cells)} cells)")
        return 0

    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(nb.cells)} cells, {len(text) / 1024:.1f} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
