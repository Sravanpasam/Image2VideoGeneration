def read(relative: str) -> str:
    return (ROOT / relative).read_text(encoding="utf-8").replace("\r\n", "\n")


def md(text: str):
    return nbf.v4.new_markdown_cell(text.strip("\n"))


def code(text: str):
    return nbf.v4.new_code_cell(text.strip("\n"))


def writefile_cell(relative: str) -> object:
    """A ``%%writefile`` cell that recreates ``relative`` byte for byte."""
    content = read(relative)
    return nbf.v4.new_code_cell(f"%%writefile {PROJECT}/{relative}\n{content}")


